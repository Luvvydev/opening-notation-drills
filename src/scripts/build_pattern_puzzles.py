#!/usr/bin/env python3
"""Generate a compact ChessDrills pack from the CC0 Lichess puzzle CSV on stdin."""
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

THEMES = ("mateIn1", "fork", "pin", "hangingPiece")
BUCKET_SIZE = 100


def main():
    buckets = defaultdict(list)
    for row in csv.DictReader(sys.stdin):
        if not row.get("NbPlays"):
            continue
        rating = int(row["Rating"])
        if not 500 <= rating < 1800:
            continue
        if int(row["Popularity"]) < 65 or int(row["RatingDeviation"]) > 110 or int(row["NbPlays"]) < 200:
            continue
        moves = row["Moves"].split()
        if len(moves) not in (2, 4, 6):
            continue
        tags = row["Themes"].split()
        themes = [theme for theme in THEMES if theme in tags]
        if not themes:
            continue
        level = rating // 100 * 100
        puzzle = [row["PuzzleId"], row["FEN"], row["Moves"], rating, themes]
        for theme in themes:
            bucket = buckets[level, theme]
            if len(bucket) < BUCKET_SIZE:
                bucket.append(puzzle)

    levels = defaultdict(dict)
    for (level, _), puzzles in buckets.items():
        for puzzle in puzzles:
            levels[level][puzzle[0]] = puzzle
    output = {level: sorted(puzzles.values(), key=lambda puzzle: puzzle[0]) for level, puzzles in sorted(levels.items())}
    if not output:
        raise SystemExit("No suitable puzzles were found.")
    target = Path(__file__).resolve().parents[1] / "data" / "patternPuzzles.js"
    with target.open("w", encoding="utf-8") as stream:
        stream.write("// Lichess Open Database (CC0). Generated by build_pattern_puzzles.py.\n")
        stream.write("export default {\n")
        for level, puzzles in output.items():
            stream.write(f"  {level}: [\n")
            for puzzle in puzzles:
                stream.write("    " + json.dumps(puzzle, separators=(",", ":")) + ",\n")
            stream.write("  ],\n")
        stream.write("};\n")
    print(" ".join(f"{level}:{len(puzzles)}" for level, puzzles in output.items()))


if __name__ == "__main__":
    main()
